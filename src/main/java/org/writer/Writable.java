package org.writer;

import java.util.List;

/**
 * Общий контракт для компонентов, сохраняющих коллекции доменных объектов в файл.
 *
 * <p>Реализации сами определяют, как объекты преобразуются перед записью на диск,
 * например, в формат CSV, JSON или другой формат отчёта.
 */
public interface Writable {

    /**
     * Записывает переданные объекты в целевой файл.
     *
     * @param data объекты для сохранения; ожидаемые ограничения определяются конкретной реализацией
     * @param fileName путь к целевому файлу
     * @throws IllegalArgumentException если имя целевого файла некорректно или входные данные не могут быть обработаны
     * @throws RuntimeException если реализации не удалось записать содержимое на диск
     */
    void writeToFile(List<?> data, String fileName);

}
